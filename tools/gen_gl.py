"""Generate guest->host OpenGL entry points (runtime/gl/gl_entry.c, gl_impl.h).

For every gl* name the game can request (strings in CoDSP.exe) that the macOS SDK declares, emit a stdcall
wrapper `glw_NAME(Cpu*)` that decodes arguments from the guest stack (float bits, 8-byte doubles, guest
pointers -> host pointers) and calls `impl_NAME(...)` if a host implementation exists (weak symbol), else logs once.
Pointer return values are guest addresses (uint32_t) in impl_ signatures.

usage: python -I tools/gen_gl.py analysis/CoDSP.exe runtime/gl
"""
import os
import re
import subprocess
import sys

exe, outdir = sys.argv[1], sys.argv[2]
sdk = subprocess.check_output(['xcrun', '--show-sdk-path'], text=True).strip()
hdr = os.path.join(sdk, 'System/Library/Frameworks/OpenGL.framework/Headers')
data = open(exe, 'rb').read()
names = set(m.decode() for m in re.findall(rb'(?<![A-Za-z0-9_])(gl[A-Z][A-Za-z0-9]+)\x00', data))

protos = {}
for f in ('gl.h', 'glext.h'):
    for line in open(os.path.join(hdr, f)):
        m = re.match(r'\s*extern\s+(.+?)\s*\b(gl[A-Z]\w*)\s*\((.*?)\)', line)
        if m and m.group(2) not in protos:
            protos[m.group(2)] = (m.group(1).strip(), m.group(3).strip())

DOUBLE = {'GLdouble', 'GLclampd'}
FLOAT = {'GLfloat', 'GLclampf'}


def parse_args(a):
    if a in ('void', ''):
        return []
    out = []
    for k, p in enumerate(a.split(',')):
        p = p.strip()
        m = re.match(r'(.*?)(\w+)\s*$', p)
        if not m or not m.group(1).strip() or m.group(2).startswith('GL'):   # unnamed parameter
            typ, nm = p, f'a{k}'
        else:
            typ, nm = m.group(1).strip(), m.group(2)
        out.append((typ, nm))
    return out


emitted = []
defaults = []
impl_h = ['// generated by tools/gen_gl.py', '#pragma once', '#include <stdint.h>', '#include "gl_types.h"', '']
entry = ['// generated by tools/gen_gl.py -- guest stdcall wrappers for opengl32 exports', '#include "../rt.h"',
         '#include "gl_impl.h"', '#include <string.h>', '', 'void gl_missing(const char *name);', '']
for name in sorted(names):
    if name not in protos:
        continue
    ret, args = protos[name]
    args = parse_args(args)
    ptr_ret = '*' in ret
    cret = 'uint32_t' if ptr_ret else ret
    sig = ', '.join(f'{t} {n}' for t, n in args) or 'void'
    impl_h.append(f'{cret} impl_{name}({sig});')
    # weak default: real implementations in gl_core.c override it
    defaults.append(f'__attribute__((weak)) {cret} impl_{name}({sig}) {{ ' +
                    ''.join(f'(void){n}; ' for _, n in args) + f'gl_missing("{name}");' +
                    ('' if cret == 'void' else ' return 0;') + ' }')
    off = 0
    dec = []
    callargs = []
    for t, n in args:
        if '*' in t:
            dec.append(f'    uint32_t g_{n} = g_rd32(sp + {off}); {t} {n} = g_{n} ? ({t})(void *)gptr(g_{n}) : NULL;')
            off += 4
        elif t in DOUBLE:
            dec.append(f'    {t} {n}; {{ uint64_t b = (uint64_t)g_rd32(sp + {off}) | ((uint64_t)g_rd32(sp + {off + 4}) << 32); memcpy(&{n}, &b, 8); }}')
            off += 8
        elif t in FLOAT:
            dec.append(f'    {t} {n}; {{ uint32_t b = g_rd32(sp + {off}); memcpy(&{n}, &b, 4); }}')
            off += 4
        else:
            dec.append(f'    {t} {n} = ({t})g_rd32(sp + {off});')
            off += 4
        callargs.append(n)
    body = [f'void glw_{name}(Cpu *cpu) {{', '    uint32_t sp = cpu->esp + 4; (void)sp;'] + dec
    call = f'impl_{name}({", ".join(callargs)})'
    if ret == 'void':
        body.append(f'    {call};')
    else:
        body.append(f'    cpu->eax = (uint32_t){call};')
    body.append(f'    cpu->esp += 4 + {off};')
    body.append('}')
    entry += body
    emitted.append(name)
entry.append('')
entry += defaults
entry.append('')
entry.append('const struct GlEntry { const char *name; GuestFn fn; } g_gl_entries[] = {')
entry += [f'    {{"{n}", glw_{n}}},' for n in emitted]
entry.append('};')
entry.append(f'const uint32_t g_gl_entry_count = {len(emitted)};')
open(os.path.join(outdir, 'gl_impl.h'), 'w').write('\n'.join(impl_h) + '\n')
open(os.path.join(outdir, 'gl_entry.c'), 'w').write('\n'.join(entry) + '\n')
print(f'{len(emitted)} entry points ({len(names) - len(emitted)} requested names unknown to the SDK headers)')
